/* dxbc2msl.c - Direct3D shader bytecode -> Metal Shading Language. See dxbc2msl.h.
 *
 * The bytecode ("DXBC" container, chunk "SHEX") is a list of 32-bit tokens for a simple register machine: registers
 * r0, r1, ... hold 4 x 32 bits with no type. Every instruction becomes one statement. Registers are kept as uint4
 * so bit patterns survive exactly; an instruction that works on floats reinterprets the bits (F(x)), computes,
 * and stores the bits back (U(x)).
 *
 * Test (Windows or Mac): build with -DDXBC2MSL_TEST and run it on the exe; it translates all 45 pixel shaders and
 * compares the result with aw_shaders.metal from the Python translator.
 */
#define _CRT_SECURE_NO_WARNINGS
#include "dxbc2msl.h"
#include <stdarg.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* ------------------------------------------------------------------ a growing string */
typedef struct { char *s; size_t len, cap; } str;

static void str_add(str *b, const char *text) {
    size_t n = strlen(text);
    if (b->len + n + 1 > b->cap) {
        b->cap = (b->len + n + 1) * 2;
        b->s = realloc(b->s, b->cap);
    }
    memcpy(b->s + b->len, text, n + 1);
    b->len += n;
}

static void str_addf(str *b, const char *fmt, ...) {
    char tmp[2048];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(tmp, sizeof tmp, fmt, ap);
    va_end(ap);
    str_add(b, tmp);
}

/* ------------------------------------------------------------------ the shared head of the Metal source */
